# make_dev_fixture.ps1 — Generate TTS development fixtures using Windows SAPI.
#
# These are dev fixtures ONLY: never in the dataset, never used to tune
# thresholds, never reported in evaluation.
#
# Usage: powershell -ExecutionPolicy Bypass -File scripts\make_dev_fixture.ps1

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Speech

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$outDir = Join-Path $scriptDir "..\backend\dev_fixtures"
if (-not (Test-Path $outDir)) {
    New-Item -ItemType Directory -Path $outDir -Force | Out-Null
}
$outDir = (Resolve-Path $outDir).Path

$passage = @'
The art of clear communication is one of the most valuable skills a person can develop. Whether speaking to a small group or addressing a large audience, the ability to convey ideas with precision and confidence makes a lasting impression. Good speakers pay attention to their pacing, ensuring that each word has time to land before moving to the next thought. They use pauses strategically, giving listeners a moment to absorb important points. Vocal variety keeps the audience engaged, while a monotone delivery can quickly lose their attention. Practice and awareness are the foundations of effective public speaking.
'@

# Save passage
[System.IO.File]::WriteAllText((Join-Path $outDir "passage.txt"), $passage.Trim(), [System.Text.UTF8Encoding]::new($false))

# Mono 22050 Hz 16-bit PCM
$format = New-Object System.Speech.AudioFormat.SpeechAudioFormatInfo(
    22050,
    [System.Speech.AudioFormat.AudioBitsPerSample]::Sixteen,
    [System.Speech.AudioFormat.AudioChannel]::Mono
)

# --- tts_ideal.wav: default rate ---
Write-Host "Generating tts_ideal.wav (default rate)..."
$synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
$synth.Rate = 0
$synth.SetOutputToWaveFile((Join-Path $outDir "tts_ideal.wav"), $format)
$synth.Speak($passage.Trim())
$synth.Dispose()
Write-Host "  Done."

# --- tts_pauses.wav: three 2.0 s SSML breaks ---
Write-Host "Generating tts_pauses.wav (three 2 s breaks)..."
$ssml = @'
<speak version="1.0" xmlns="http://www.w3.org/2001/10/synthesis" xml:lang="en-US">
The art of clear communication is one of the most valuable skills a person can develop.
<break time="2000ms"/>
Whether speaking to a small group or addressing a large audience, the ability to convey ideas with precision and confidence makes a lasting impression.
<break time="2000ms"/>
Good speakers pay attention to their pacing, ensuring that each word has time to land before moving to the next thought. They use pauses strategically, giving listeners a moment to absorb important points.
<break time="2000ms"/>
Vocal variety keeps the audience engaged, while a monotone delivery can quickly lose their attention. Practice and awareness are the foundations of effective public speaking.
</speak>
'@
$synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
$synth.Rate = 0
$synth.SetOutputToWaveFile((Join-Path $outDir "tts_pauses.wav"), $format)
$synth.SpeakSsml($ssml)
$synth.Dispose()
Write-Host "  Done."

# --- tts_fast.wav: clearly faster rate ---
Write-Host "Generating tts_fast.wav (Rate = 5)..."
$synth = New-Object System.Speech.Synthesis.SpeechSynthesizer
$synth.Rate = 5
$synth.SetOutputToWaveFile((Join-Path $outDir "tts_fast.wav"), $format)
$synth.Speak($passage.Trim())
$synth.Dispose()
Write-Host "  Done."

# --- Ground-truth JSON for pause positions ---
$json = @'
{
  "note": "SSML break positions in tts_pauses.wav. Actual timing depends on the TTS engine. Dev fixture only.",
  "breaks": [
    {
      "after_text": "a person can develop.",
      "break_duration_ms": 2000,
      "sentence_boundary": "end of sentence 1"
    },
    {
      "after_text": "makes a lasting impression.",
      "break_duration_ms": 2000,
      "sentence_boundary": "end of sentence 2"
    },
    {
      "after_text": "absorb important points.",
      "break_duration_ms": 2000,
      "sentence_boundary": "end of sentence 4"
    }
  ]
}
'@
[System.IO.File]::WriteAllText((Join-Path $outDir "pauses_ground_truth.json"), $json, [System.Text.UTF8Encoding]::new($false))

# --- README ---
$readme = @'
# dev_fixtures

Development-only TTS fixtures for testing the SpeechLens pipeline.

These files are **not** part of the dataset. They must never be used to tune
thresholds or reported in evaluation. They exist solely so the pipeline can be
exercised end-to-end before real recordings are available.

Generated by `scripts/make_dev_fixture.ps1` using Windows System.Speech (SAPI).

## Files

- `passage.txt` — the ~100-word passage used for all three renderings.
- `tts_ideal.wav` — default rate, no inserted pauses.
- `tts_pauses.wav` — same text with three 2.0 s SSML breaks.
- `tts_fast.wav` — same text at SpeechSynthesizer.Rate = 5.
- `pauses_ground_truth.json` — positions of the inserted SSML breaks.

This folder is in .gitignore.
'@
[System.IO.File]::WriteAllText((Join-Path $outDir "README.md"), $readme, [System.Text.UTF8Encoding]::new($false))

Write-Host "`nAll fixtures written to $outDir"
Get-ChildItem $outDir | Format-Table Name, Length -AutoSize
